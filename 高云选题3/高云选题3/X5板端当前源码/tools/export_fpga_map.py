"""Export the authoritative FPGA raster and destinations for the HMI.

No screen capture, road-width approximation, or inferred live location.
Run whenever FPGA ROM/destinations change; commit generated artifacts together.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib

WS = Path(__file__).resolve().parents[1]
DEFAULT_FPGA = WS.parents[1] / 'ov5640'


def export(fpga=DEFAULT_FPGA, workspace=WS):
    fpga, workspace = Path(fpga), Path(workspace)
    source = fpga / 'src/navigation/nav_map_init.vh'
    destination = fpga / 'src/navigation/nav_destinations.vh'
    values = [(int(i), int(v, 16)) for i, v in re.findall(
        r"raw_map\[(\d+)\]\s*=\s*16'h([0-9a-fA-F]+)", source.read_text())]
    if len(values) != 7040 or sorted(i for i, _ in values) != list(range(7040)):
        raise ValueError('FPGA raw raster must contain exactly 7040 unique words')
    words = [v for _, v in sorted(values)]
    bitmap = bytes((word >> bit) & 1 for word in words for bit in range(16))
    flat = (fpga / 'src/navigation/map_raw_1cm.mem').read_text().split()
    if bitmap != bytes(int(value, 2) for value in flat):
        raise ValueError('map_raw_1cm.mem differs from compiled nav_map_init.vh')
    coords = {int(i): (int(x), int(y)) for i, y, x in re.findall(
        r"(\d+):nav_destination=\{8'd(\d+),8'd(\d+)\}", destination.read_text())}
    if set(coords) != set(range(1, 10)):
        raise ValueError('expected nine authoritative destinations')
    points = json.loads((workspace / 'config/numbered_points.json').read_text(encoding='utf-8-sig'))['points']
    exported_points = []
    for point in points:
        ident = point['id']
        x, y = coords[ident]
        if point['planner_cell'] != [x, y] or point['display_cm'] != [2*x+1, 319-2*y]:
            raise ValueError('numbered_points.json disagrees with FPGA destinations')
        exported_points.append(dict(id=ident, label=f'{ident}号点', location=point['location'],
            raster_cm=dict(x=2*x+1, y=2*y+1), display_cm=dict(x=2*x+1, y=319-2*y)))
    if len(exported_points) != 9 or len({p['id'] for p in exported_points}) != 9:
        raise ValueError('destination catalog duplicates or omits points')
    runs = []
    for row in range(320):
        start = None
        for column in range(353):
            road = column < 352 and bitmap[row*352+column] == 0
            if road and start is None:
                start = column
            if not road and start is not None:
                runs.append([row, start, column-start])
                start = None
    # Versioned identity bytes: exact bit-packed little-endian ROM words plus
    # numbered planner cells. The same constant is compiled into new RTL.
    identity = b'FPGA_MAP_V1\0' + struct.pack('<7040H', *words)
    identity += bytes(value for ident in range(1, 10) for value in (ident, *coords[ident]))
    signature = zlib.crc32(identity) & 0xffffffff
    sources = {str(p.relative_to(fpga)).replace('\\', '/'): hashlib.sha256(p.read_bytes()).hexdigest()
               for p in (source, destination, fpga/'src/navigation/map_raw_1cm.mem')}
    catalog = dict(schema_version=1, map_signature=signature,
        map_signature_hex=f'{signature:08x}', signature_algorithm='crc32_FPGA_MAP_V1_rom_words_le16_numbered_cells',
        source='FPGA compiled ROM', source_hashes=sources,
        firmware_map_verified=False,
        geometry=dict(width_cm=352, height_cm=320, cell_cm=1, origin='top_left', y_axis='down', road_runs=runs),
        points=exported_points,
        limits=['Static map identity is checked only after real UART capability/signature replies.',
                'Pose is encoder/IMU dead reckoning, not externally measured absolute localization.',
                'The nominal map geometry is exactly the compiled raster; physical road-width settings do not redraw it.'])
    target = workspace / 'config/fpga_map_catalog.json'
    target.write_text(json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))+'\n', encoding='utf-8')
    asset = workspace / 'web/assets/fpga_map.svg'
    asset.parent.mkdir(parents=True, exist_ok=True)
    path = ''.join(f'M{x} {y}h{length}v1h-{length}z' for y, x, length in runs)
    asset.write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 352 320">'
                     '<rect width="352" height="320" fill="#151e27"/>'
                     f'<path d="{path}" fill="#668493"/></svg>\n', encoding='utf-8')
    (fpga/'src/navigation/nav_host_map_id.vh').write_text(
        '// Generated by ros2_ws/tools/export_fpga_map.py; exact ROM + numbered cells.\n'
        f"localparam [31:0] HOST_MAP_SIGNATURE=32'h{signature:08x};\n", encoding='ascii')
    return catalog


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fpga', type=Path, default=DEFAULT_FPGA)
    parser.add_argument('--workspace', type=Path, default=WS)
    args = parser.parse_args()
    result = export(args.fpga, args.workspace)
    print(json.dumps(dict(signature=result['map_signature_hex'], roads=len(result['geometry']['road_runs']), points=len(result['points']))))
