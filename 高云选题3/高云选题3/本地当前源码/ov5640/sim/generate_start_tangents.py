"""Derive each directed graph alias's departure tangent; geometry is unchanged."""
from pathlib import Path
import functools
import hashlib
import math
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'src/navigation/nav_centerline_init.vh'
words = [int(x, 16) for x in re.findall(r"=79'h([0-9a-fA-F]+)", source.read_text())]

def xy(i):
    return words[i] & 0x1ffff, (words[i] >> 17) & 0x1ffff

def neighbors(i):
    return [n for j in range(3) if (n := (words[i] >> (34+j*15)) & 2047) != 2047]

@functools.lru_cache(None)
def directions(i):
    x, y = xy(i)
    result = []
    for n in neighbors(i):
        nx, ny = xy(n)
        if (nx, ny) == (x, y):
            result.extend(directions(n))
        else:
            result.append(math.atan2(y-ny, nx-x))  # Map world Y is up.
    return tuple(result)

lines = ['// Generated by sim/generate_start_tangents.py; degrees, X right/Y up.',
         '// Graph SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
         '// 9-bit signed degrees fit one 2048x9 BSRAM; +255 means no departure.']
for index in range(len(words)):
    angles = directions(index)
    if angles:
        angle = round(math.degrees(math.atan2(sum(map(math.sin, angles)), sum(map(math.cos, angles)))))
        assert all(abs((math.degrees(a)-angle+180) % 360-180) <= 15 for a in angles)
    else:
        angle = 255
    lines.append(f"start_tangent[{index}]=9'h{angle & 511:03x};")
output = '\n'.join(lines)+'\n'
target = ROOT/'src/navigation/nav_centerline_heading.vh'
if '--write' in sys.argv:
    target.write_text(output, encoding='ascii')
else:
    assert target.read_text(encoding='ascii') == output, 'Regenerate tangent ROM after graph changes'
print('PASS directed tangent ROM:', len(words), 'aliases; graph unchanged')
